begin;
do $$
declare a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); viewer uuid:=gen_random_uuid(); org uuid; other_org uuid; agent uuid; social uuid; request_key uuid:=gen_random_uuid(); claimed jsonb; denied boolean; result jsonb;
begin
 insert into auth.users(id,email) values(a,'browser-a@example.invalid'),(b,'browser-b@example.invalid'),(viewer,'browser-viewer@example.invalid');
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 org:=public.create_vendor_workspace('Browser test A');
 select id into agent from public.platform_agents where organization_id=org and platform='web';
 select id into social from public.platform_agents where organization_id=org and platform='facebook';
 insert into public.browser_sites values(org,'https://example.com',a,now());
 denied:=false;
 begin perform public.claim_browser_operation(a,org,agent,request_key,'start'); exception when insufficient_privilege then denied:=true; end;
 if not denied then raise exception 'Client obtained browser runtime secrets'; end if;
 execute 'reset role';
 insert into public.organization_members values(org,viewer,'viewer');
 execute 'set local role service_role';
 denied:=false;
 begin perform public.claim_browser_operation(viewer,org,agent,request_key,'start'); exception when others then denied:=true; end;
 if not denied then raise exception 'Viewer provisioned browser'; end if;
 denied:=false;
 begin perform public.claim_browser_operation(a,org,social,request_key,'start'); exception when others then denied:=true; end;
 if not denied then raise exception 'Unsupported social browser started'; end if;
 claimed:=public.claim_browser_operation(a,org,agent,request_key,'start');
 denied:=false;
 begin perform public.claim_browser_operation(a,org,agent,gen_random_uuid(),'takeover'); exception when others then denied:=true; end;
 if not denied then raise exception 'Concurrent control lease granted'; end if;
 result:=jsonb_build_object('state','ready','origin','https://example.com','task','Review a local resource','providerSession',gen_random_uuid(),'profileId',gen_random_uuid(),'expiresAt',now()+interval '5 minutes');
 perform public.finish_browser_operation(request_key,result,true);
 denied:=false;
 begin perform public.claim_browser_operation(a,org,agent,request_key,'start'); exception when others then denied:=true; end;
 if not denied then raise exception 'Duplicate request replayed'; end if;
 request_key:=gen_random_uuid();
 perform public.claim_browser_operation(a,org,agent,request_key,'navigate');
 execute 'reset role';
 update private.browser_runtime set operation_until=now()-interval '1 second' where workspace_id=(claimed->'workspace'->>'id')::uuid;
 execute 'set local role service_role';
 denied:=false;
 begin perform public.finish_browser_operation(request_key,result,true); exception when others then denied:=true; end;
 if not denied then raise exception 'Expired worker updated current session'; end if;
 denied:=false;
 begin perform public.claim_browser_operation(a,org,agent,gen_random_uuid(),'takeover'); exception when others then denied:=true; end;
 if not denied then raise exception 'Uncertain browser action allowed takeover'; end if;
 perform public.claim_browser_operation(a,org,agent,gen_random_uuid(),'disconnect');
 execute 'reset role';
 perform set_config('request.jwt.claims',jsonb_build_object('sub',viewer,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 denied:=false;
 begin insert into public.browser_sites values(org,'https://unauthorized.invalid',viewer,now()); exception when insufficient_privilege then denied:=true; end;
 if not denied then raise exception 'Viewer authorized website'; end if;
 denied:=false;
 begin update public.browser_workspaces set state='human_controlling' where agent_id=agent; exception when insufficient_privilege then denied:=true; end;
 if not denied then raise exception 'Client forged browser state'; end if;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b,'role','authenticated')::text,true);
 other_org:=public.create_vendor_workspace('Browser test B');
 if exists(select 1 from public.browser_workspaces) or exists(select 1 from public.browser_actions) or exists(select 1 from public.browser_sites) then raise exception 'Cross-tenant browser visibility'; end if;
 execute 'reset role';
 execute 'set local role service_role';
 denied:=false;
 begin perform public.claim_browser_operation(b,other_org,agent,gen_random_uuid(),'observe'); exception when others then denied:=true; end;
 if not denied then raise exception 'Cross-tenant browser operation allowed'; end if;
end $$;
rollback;
