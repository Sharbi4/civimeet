begin;
do $$
declare
 a uuid:=gen_random_uuid(); b uuid:=gen_random_uuid(); viewer uuid:=gen_random_uuid(); organizer uuid:=gen_random_uuid();
 org uuid; other_org uuid; vendor uuid:=gen_random_uuid(); other_vendor uuid:=gen_random_uuid(); event uuid; cost uuid; extra uuid; body jsonb; denied boolean;
begin
 insert into auth.users(id,email) values(a,'event-a@example.invalid'),(b,'event-b@example.invalid'),(viewer,'event-viewer@example.invalid'),(organizer,'event-organizer@example.invalid');
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 org:=public.create_vendor_workspace('Event test A');
 if (select count(distinct instructions) from public.platform_agents where organization_id=org)<>7 then raise exception 'Platform-specific defaults missing'; end if;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b,'role','authenticated')::text,true);
 other_org:=public.create_vendor_workspace('Event test B');
 execute 'reset role';
 insert into public.vendors(id,organization_id,name) values(vendor,org,'Test caterer'),(other_vendor,other_org,'Other caterer');
 insert into public.organization_members values(org,viewer,'viewer'),(org,organizer,'organizer');
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 body:=jsonb_build_object('title','Community workshop','purpose','Bring neighbors together to learn practical skills.','event_date',current_date+10,'budget_cents',10000);
 event:=public.save_community_event(org,body);
 denied:=false;
 begin update public.community_events set budget_cents=999999 where id=event; exception when insufficient_privilege then denied:=true; end;
 if not denied then raise exception 'Direct client event write allowed'; end if;
 denied:=false;
 begin perform public.propose_event_payment(event,other_vendor,'Wrong tenant vendor',100,'https://example.invalid/quote'); exception when others then denied:=true; end;
 if not denied then raise exception 'Cross-tenant vendor accepted'; end if;
 cost:=public.propose_event_payment(event,vendor,'Workshop catering',6000,'https://example.invalid/quote');
 extra:=public.propose_event_payment(event,vendor,'Extra service',5000,'https://example.invalid/extra');
 denied:=false;
 begin perform public.review_event_payment(cost,'approve'); exception when others then denied:=true; end;
 if not denied then raise exception 'Draft event cost approved'; end if;
 perform public.review_community_event(event,1,'approve');
 perform public.review_event_payment(cost,'approve');
 denied:=false;
 begin perform public.review_event_payment(extra,'approve'); exception when others then denied:=true; end;
 if not denied then raise exception 'Aggregate budget exceeded'; end if;
 perform public.save_community_event(org,body,event,1);
 if exists(select 1 from public.event_payment_requests where event_id=event and status in ('proposed','approved')) then raise exception 'Edit kept stale costs'; end if;
 denied:=false;
 begin perform public.review_community_event(event,1,'approve'); exception when others then denied:=true; end;
 if not denied then raise exception 'Stale event approved'; end if;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',organizer,'role','authenticated')::text,true);
 denied:=false;
 begin perform public.review_community_event(event,2,'approve'); exception when others then denied:=true; end;
 if not denied then raise exception 'Organizer approved event'; end if;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',viewer,'role','authenticated')::text,true);
 denied:=false;
 begin perform public.save_community_event(org,body); exception when others then denied:=true; end;
 if not denied then raise exception 'Viewer created event'; end if;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',b,'role','authenticated')::text,true);
 if exists(select 1 from public.community_events) or exists(select 1 from public.event_payment_requests) then raise exception 'Cross-tenant data visible'; end if;
 denied:=false;
 begin perform public.review_community_event(event,2,'approve'); exception when others then denied:=true; end;
 if not denied then raise exception 'Cross-tenant approval allowed'; end if;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',a,'role','authenticated')::text,true);
 perform public.review_community_event(event,2,'approve');
 cost:=public.propose_event_payment(event,vendor,'Revised catering',4000,'https://example.invalid/revised');
 perform public.review_event_payment(cost,'approve');
 perform public.review_community_event(event,2,'cancel');
 if exists(select 1 from public.event_payment_requests where event_id=event and status='approved') then raise exception 'Cancelled event retained commitments'; end if;
end $$;
rollback;
