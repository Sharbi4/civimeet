begin;
do $$
declare owner_id uuid:=gen_random_uuid(); other_id uuid:=gen_random_uuid(); org uuid; ev uuid; ag uuid; first_id uuid; second_id uuid; ids jsonb; claimed jsonb; lease uuid; original_request uuid; blocked boolean;
begin
 insert into auth.users(id,email) values(owner_id,'work-owner@example.invalid'),(other_id,'work-other@example.invalid');
 perform set_config('request.jwt.claims',jsonb_build_object('sub',owner_id,'role','authenticated')::text,true);
 execute 'set local role authenticated';org:=public.create_vendor_workspace('Agent runner tests');execute 'reset role';
 insert into public.organization_briefs(organization_id,coordinator,area,mission,voice) values(org,'Demo','Tucson','Help local neighbors find resources','Helpful');
 update public.platform_agents set selected=true,paused=false where organization_id=org and platform='web' returning id into ag;
 execute 'set local role authenticated';
 ev:=public.save_community_event(org,'{"title":"Demo gathering","purpose":"Help neighbors meet local partners","event_date":"2027-04-01","geographic_area":"Orlando, Florida","budget_cents":0}');
 ids:=public.queue_event_groundwork(ev);first_id:=(ids->>0)::uuid;second_id:=(ids->>1)::uuid;
 perform public.queue_event_groundwork(ev);
 if (select count(*) from public.agent_work_items where event_id=ev)<>2 then raise exception 'Duplicate event work';end if;
 blocked:=false;begin perform public.claim_editor_agent_work(owner_id,org,first_id);exception when insufficient_privilege then blocked:=true;end;
 if not blocked then raise exception 'Client called privileged claim';end if;
 execute 'reset role';
 blocked:=false;begin perform public.claim_editor_agent_work(other_id,org,first_id);exception when others then blocked:=true;end;
 if not blocked then raise exception 'Cross-org work allowed';end if;
 blocked:=false;begin perform public.claim_editor_agent_work(owner_id,org,second_id);exception when others then blocked:=true;end;
 if not blocked then raise exception 'Dependency ignored';end if;
 claimed:=public.claim_editor_agent_work(owner_id,org,first_id);lease:=(claimed->'task'->>'lease_id')::uuid;original_request:=(claimed->'task'->>'research_request_id')::uuid;
 blocked:=false;begin perform public.claim_editor_agent_work(owner_id,org,first_id);exception when others then blocked:=true;end;
 if not blocked then raise exception 'Concurrent lease accepted';end if;
 update public.agent_work_items set lease_until=now()-interval '1 second' where id=first_id;
 claimed:=public.claim_editor_agent_work(owner_id,org,first_id);
 if (claimed->'task'->>'research_request_id')::uuid<>original_request then raise exception 'Recovery changed request identity';end if;
 blocked:=false;begin perform public.finish_editor_agent_work(owner_id,org,first_id,lease,true,'Old result');exception when others then blocked:=true;end;
 if not blocked then raise exception 'Stale worker finished';end if;
 lease:=(claimed->'task'->>'lease_id')::uuid;
 perform public.finish_editor_agent_work(owner_id,org,first_id,lease,true,'Community research saved; nothing posted.');
 if not (public.claim_editor_agent_work(owner_id,org,first_id)->>'replayed')::boolean then raise exception 'Completed task repeated';end if;
 if not exists(select 1 from public.agent_memory where agent_id=ag and memory_key='work:'||first_id) then raise exception 'No checkpoint';end if;
 claimed:=public.claim_editor_agent_work(owner_id,org,second_id);lease:=(claimed->'task'->>'lease_id')::uuid;
 perform public.finish_editor_agent_work(owner_id,org,second_id,lease,false,'Provider limit reached');
 execute 'set local role authenticated';perform public.retry_agent_research(second_id);execute 'reset role';
 if (select status from public.agent_work_items where id=second_id)<>'queued' then raise exception 'Explicit retry failed';end if;
 update public.platform_agents set paused=true where id=ag;
 blocked:=false;begin perform public.claim_editor_agent_work(owner_id,org,second_id);exception when others then blocked:=true;end;
 if not blocked then raise exception 'Paused agent executed';end if;
end; $$;
rollback;
